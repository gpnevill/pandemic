// Generates src/game/world.ts — an SVG path of world landmasses projected
// into the game's 1600x900 viewBox (Miller projection, lat clamped to [-56, 74]).
// Run: node scripts/genWorld.mjs
import * as topojson from 'topojson-client';
import fs from 'node:fs';

const W = 1600;
const H = 900;
const LAT_TOP = 74;
const LAT_BOT = -56;

const rad = (d) => (d * Math.PI) / 180;
const millerY = (lat) => 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * rad(lat)));
const Y_TOP = millerY(LAT_TOP);
const Y_BOT = millerY(LAT_BOT);

function project(lon, lat) {
  const x = ((lon + 180) / 360) * W;
  const clamped = Math.max(LAT_BOT, Math.min(LAT_TOP, lat));
  const y = ((Y_TOP - millerY(clamped)) / (Y_TOP - Y_BOT)) * H;
  return [x, y];
}

const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = topojson.feature(topo, topo.objects.land);

let d = '';
for (const feature of land.features ?? [land]) {
  const geom = feature.geometry ?? feature;
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      const pts = ring.map(([lon, lat]) => project(lon, lat));
      // drop antarctic slivers fully below the clamp line
      if (pts.every(([, y]) => y >= H - 1)) continue;
      // split where the ring jumps across the antimeridian, otherwise a
      // horizontal line gets drawn across the whole map
      const segments = [[pts[0]]];
      for (let i = 1; i < pts.length; i++) {
        if (Math.abs(pts[i][0] - pts[i - 1][0]) > W / 2) segments.push([]);
        segments.at(-1).push(pts[i]);
      }
      for (const seg of segments) {
        if (seg.length < 3) continue;
        d += 'M' + seg.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + 'Z';
      }
    }
  }
}

const out = `// AUTO-GENERATED by scripts/genWorld.mjs — do not edit by hand.
export const WORLD_PATH = ${JSON.stringify(d)};
`;
fs.writeFileSync('src/game/world.ts', out);
console.log(`world.ts written, ${(d.length / 1024).toFixed(1)} KB of path data`);
